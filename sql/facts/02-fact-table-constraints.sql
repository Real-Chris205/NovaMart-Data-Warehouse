-- 1. FACT SALES

-- Configure automatic generation of the sales surrogate key

ALTER TABLE Fact_sales
ALTER COLUMN sales_key
ADD GENERATED BY DEFAULT AS IDENTITY;


-- Enforce the sales amount calculation rule

ALTER TABLE Fact_sales
ADD CONSTRAINT chk_fact_sales_amount_formula
CHECK (
    sales_amount =
    (quantity * unit_price) - COALESCE(discount_amount, 0)
);


-- 2. FACT PAYMENT

-- Configure automatic generation of the payment surrogate key

ALTER TABLE fact_payment
ALTER COLUMN payment_key
ADD GENERATED BY DEFAULT AS IDENTITY;


-- 3. FACT PRODUCT PRICE HISTORY

-- Configure automatic generation of the price-history surrogate key

ALTER TABLE fact_product_pricehistory
ALTER COLUMN price_history_key
ADD GENERATED BY DEFAULT AS IDENTITY;


-- Allow NULL product keys for historical records
-- that fall outside the available product dimension baseline

ALTER TABLE Fact_Product_PriceHistory
ALTER COLUMN product_key DROP NOT NULL;
